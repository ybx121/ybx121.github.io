import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import MarkdownIt from 'markdown-it';

const source = new URL('./blog/', import.meta.url);
const output = new URL('./dist/blog/', import.meta.url);
const postOutput = new URL('posts/', output);
const generated = '<!-- Generated by build-blog.mjs -->\n';
const slugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const markdown = new MarkdownIt({ html: false });
const escape = markdown.utils.escapeHtml;
const description = '记录计算机科学学习、研究笔记和项目实践。';

const entries = JSON.parse(await readFile(new URL('posts.json', source), 'utf8'));
if (!Array.isArray(entries)) throw new Error('blog/posts.json must contain an array.');

const slugs = new Set();
const posts = await Promise.all(entries.map(async (entry, index) => {
  const { slug, title, date, summary = '', tags = [] } = entry ?? {};
  const validDate = typeof date === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(date)
    && new Date(`${date}T00:00:00Z`).toJSON()?.startsWith(date);
  if (typeof slug !== 'string' || !slugPattern.test(slug) || slugs.has(slug)
      || typeof title !== 'string' || !title.trim() || !validDate
      || typeof summary !== 'string' || !Array.isArray(tags)
      || tags.some(tag => typeof tag !== 'string' || !tag.trim())) {
    throw new Error(`Invalid or duplicate article at blog/posts.json entry ${index + 1}.`);
  }
  slugs.add(slug);
  const body = await readFile(new URL(`posts/${slug}.md`, source), 'utf8');
  if (!body.trim()) throw new Error(`Empty article: blog/posts/${slug}.md`);
  return { slug, title: title.trim(), date, summary, tags: [...new Set(tags.map(tag => tag.trim()))], body };
}));
posts.sort((a, b) => b.date.localeCompare(a.date));

const topics = [...new Set(posts.flatMap(post => post.tags))].sort((a, b) => a.localeCompare(b, 'zh-CN'));
const years = [...new Set(posts.map(post => post.date.slice(0, 4)))];
const topicId = tag => `topic-${topics.indexOf(tag) + 1}`;
const css = await readFile(new URL('blog.css', output));
const cssVersion = createHash('sha256').update(css).digest('hex').slice(0, 12);

function page({ title, summary, body, blogRoot = './' }) {
  return `${generated}<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escape(summary)}">
  <title>${escape(title)}</title>
  <link rel="icon" href="${blogRoot}../assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="${blogRoot}blog.css?v=${cssVersion}">
</head>
<body>
  <a class="skip-link" href="#main">跳转到正文</a>
  <header class="blog-bar">
    <div class="blog-shell bar-inner">
      <a class="blog-brand" href="${blogRoot}">杨秉熹<span>的博客</span></a>
      <nav aria-label="博客导航">
        <a href="${blogRoot}#articles">文章</a>
        ${topics.length ? `<a href="${blogRoot}#topics">标签</a>` : ''}
        ${years.length ? `<a href="${blogRoot}#archive">归档</a>` : ''}
        <a class="home-link" href="${blogRoot}../">个人主页 <span aria-hidden="true">↗</span></a>
      </nav>
    </div>
  </header>
  <main id="main" class="blog-shell">${body}</main>
  <footer class="blog-shell blog-footer">杨秉熹 <span aria-hidden="true">·</span> 文章与笔记</footer>
</body>
</html>
`;
}

function metadata(post, blogRoot) {
  return `<div class="post-meta"><time datetime="${post.date}">${post.date}</time>
    ${post.tags.map(tag => `<a class="post-tag" href="${blogRoot}#${topicId(tag)}">${escape(tag)}</a>`).join('')}
  </div>`;
}

function archiveList(items) {
  return `<ul class="archive-list">${items.map(post => `<li>
    <time datetime="${post.date}">${post.date}</time>
    <a href="posts/${post.slug}.html">${escape(post.title)}</a>
  </li>`).join('')}</ul>`;
}

const listing = posts.map(post => `<article class="post-preview">
  <h3><a href="posts/${post.slug}.html">${escape(post.title)}</a></h3>
  ${metadata(post, './')}
  ${post.summary ? `<p>${escape(post.summary)}</p>` : ''}
</article>`).join('');

const index = page({
  title: '文章与笔记 · 杨秉熹',
  summary: description,
  body: `
    <header class="blog-intro">
      <p class="blog-eyebrow" lang="en">YANG BINGXI <span aria-hidden="true">·</span> BLOG</p>
      <h1>文章与笔记</h1>
      <p class="blog-description">${description}</p>
    </header>
    <section class="blog-section" id="articles">
      <h2>最新文章</h2>
      ${listing || `<div class="blog-empty">
        <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 3h9l4 4v14H6zM14 3v5h5M9 12h7m-7 4h7"/></svg>
        <p>第一篇文章还在路上</p>
        <p>新的文章和笔记发布后，会在这里按日期显示。</p>
      </div>`}
    </section>
    ${topics.length ? `<section class="blog-section" id="topics"><h2>标签</h2>
      ${topics.map(tag => `<section class="archive-group" id="${topicId(tag)}"><h3>${escape(tag)}</h3>
        ${archiveList(posts.filter(post => post.tags.includes(tag)))}</section>`).join('')}
    </section>` : ''}
    ${years.length ? `<section class="blog-section" id="archive"><h2>归档</h2>
      ${years.map(year => `<section class="archive-group"><h3>${year}</h3>
        ${archiveList(posts.filter(post => post.date.startsWith(year)))}</section>`).join('')}
    </section>` : ''}
  `
});

await mkdir(postOutput, { recursive: true });
await Promise.all(posts.map(post => writeFile(new URL(`${post.slug}.html`, postOutput), page({
  title: `${post.title} · 杨秉熹`,
  summary: post.summary || post.title,
  blogRoot: '../',
  body: `<article class="reading-page">
    <a class="back-link" href="../#articles">← 返回文章列表</a>
    <header class="reading-header"><h1>${escape(post.title)}</h1>${metadata(post, '../')}</header>
    <div class="post-body">${markdown.render(post.body)}</div>
  </article>`
}), 'utf8')));
await writeFile(new URL('index.html', output), index, 'utf8');

for (const file of await readdir(postOutput, { withFileTypes: true })) {
  const slug = file.name.slice(0, -5);
  if (!file.isFile() || !file.name.endsWith('.html') || !slugPattern.test(slug) || slugs.has(slug)) continue;
  const path = new URL(file.name, postOutput);
  if ((await readFile(path, 'utf8')).startsWith(generated)) await unlink(path);
}

console.log(`Built /blog/ with ${posts.length} article${posts.length === 1 ? '' : 's'}.`);
